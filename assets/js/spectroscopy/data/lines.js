// Refractive index of standard air (Ciddor 1996), from a vacuum wavelength in nm
function airIndex(vacNm) {
    const s2 = (1000 / vacNm) ** 2;
    return 1 + 0.05792105 / (238.0185 - s2) + 0.00167917 / (57.362 - s2);
}

export function vacToAir(vacNm) {
    return vacNm < 200 ? vacNm : vacNm / airIndex(vacNm);
}

export function airToVac(airNm) {
    if (airNm < 200) return airNm;
    let vac = airNm;
    for (let i = 0; i < 4; i++) vac = airNm * airIndex(vac);
    return vac;
}

